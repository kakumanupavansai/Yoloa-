import os
import uuid

from django.conf import settings
from django.db import models
from django.db.models import F, Q
from django.utils import timezone

from lms.models import private_storage


class Conversation(models.Model):
    """A private one-to-one conversation between two students.

    The members are stored in id order (user_low < user_high), so a pair of students can only ever have one conversation.
    """
    user_low = models.ForeignKey(settings.AUTH_USER_MODEL, on_delete=models.CASCADE, related_name='+')
    user_high = models.ForeignKey(settings.AUTH_USER_MODEL, on_delete=models.CASCADE, related_name='+')
    created_at = models.DateTimeField(auto_now_add=True)
    last_message_at = models.DateTimeField(null=True, blank=True)

    class Meta:
        constraints = [
            models.UniqueConstraint(fields=['user_low', 'user_high'], name='one_conversation_per_student_pair'),
            models.CheckConstraint(condition=Q(user_low__lt=F('user_high')), name='conversation_members_ordered'),
        ]
        indexes = [models.Index(fields=['-last_message_at'])]

    def member_ids(self):
        return (self.user_low_id, self.user_high_id)

    def other_id(self, user_id):
        return self.user_high_id if user_id == self.user_low_id else self.user_low_id


class ConversationMember(models.Model):
    """Per-member read state. `last_read_message_id` only moves forward."""
    conversation = models.ForeignKey(Conversation, on_delete=models.CASCADE, related_name='members')
    user = models.ForeignKey(settings.AUTH_USER_MODEL, on_delete=models.CASCADE, related_name='conversation_memberships')
    last_read_message_id = models.BigIntegerField(default=0)
    last_read_at = models.DateTimeField(null=True, blank=True)

    class Meta:
        constraints = [models.UniqueConstraint(fields=['conversation', 'user'], name='one_membership_per_conversation_user')]


class Message(models.Model):
    """Messages are written to PostgreSQL before any real-time event is sent; ids increase, so clients
    recover anything they missed while offline by asking for messages after the last id they saw."""
    conversation = models.ForeignKey(Conversation, on_delete=models.CASCADE, related_name='messages')
    sender = models.ForeignKey(settings.AUTH_USER_MODEL, on_delete=models.CASCADE, related_name='sent_messages')
    body = models.TextField(blank=True)
    # Generated by the sending browser so a retried send (WebSocket, then HTTP) is stored only once.
    client_id = models.UUIDField(null=True, blank=True)
    created_at = models.DateTimeField(default=timezone.now)

    class Meta:
        ordering = ['id']
        constraints = [models.UniqueConstraint(fields=['sender', 'client_id'], condition=Q(client_id__isnull=False),
                                               name='unique_message_client_id_per_sender')]
        indexes = [models.Index(fields=['conversation', 'id'])]


def attachment_path(instance, filename):
    # Random stored name: the original name is kept in the database only, never used as a path.
    ext = os.path.splitext(filename)[1].lower()
    return timezone.now().strftime(f'chat_attachments/%Y/%m/{uuid.uuid4().hex}{ext}')


class MessageAttachment(models.Model):
    KINDS = [('image', 'Image'), ('document', 'Document')]
    message = models.ForeignKey(Message, on_delete=models.CASCADE, related_name='attachments')
    file = models.FileField(upload_to=attachment_path, storage=private_storage, max_length=255)
    original_name = models.CharField(max_length=255)
    content_type = models.CharField(max_length=120)
    size = models.PositiveIntegerField()
    kind = models.CharField(max_length=10, choices=KINDS)
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        ordering = ['id']


# ───────────────────────── Public student feed ─────────────────────────
class FeedPost(models.Model):
    """A post on the public student feed, readable by every active student.

    Kept in its own tables: nothing from private conversations is ever reachable through the feed API.
    """
    author = models.ForeignKey(settings.AUTH_USER_MODEL, on_delete=models.CASCADE, related_name='feed_posts')
    body = models.TextField(blank=True)
    link_url = models.URLField(max_length=500, blank=True)
    created_at = models.DateTimeField(default=timezone.now)

    class Meta:
        ordering = ['-id']


def feed_attachment_path(instance, filename):
    ext = os.path.splitext(filename)[1].lower()
    return timezone.now().strftime(f'feed_attachments/%Y/%m/{uuid.uuid4().hex}{ext}')


class FeedAttachment(models.Model):
    KINDS = MessageAttachment.KINDS
    post = models.ForeignKey(FeedPost, on_delete=models.CASCADE, related_name='attachments')
    file = models.FileField(upload_to=feed_attachment_path, storage=private_storage, max_length=255)
    original_name = models.CharField(max_length=255)
    content_type = models.CharField(max_length=120)
    size = models.PositiveIntegerField()
    kind = models.CharField(max_length=10, choices=KINDS)
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        ordering = ['id']
